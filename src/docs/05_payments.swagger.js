/**
 * @swagger
 * tags:
 *   name: Payments
 *   description: Razorpay order creation, payment signature verification, and 3D-Secure bank redirect callbacks.
 */

/**
 * @swagger
 * /api/payments/create-order:
 *   post:
 *     summary: Create a Razorpay payment order
 *     description: |
 *       **Purpose:** Initiates a payment session by generating an official `order_id` via the Razorpay API.
 *       The frontend uses this `order_id` to launch the Razorpay Checkout modal.
 *       **Access Level:** 🔒 Authenticated Session (PARENT).
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - amount
 *             properties:
 *               amount:
 *                 type: number
 *                 description: Order amount in INR (Indian Rupees).
 *                 example: 500
 *               currency:
 *                 type: string
 *                 default: "INR"
 *                 example: "INR"
 *               packageId:
 *                 type: string
 *                 description: Optional wallet package UUID being purchased.
 *                 example: "pkg_starter_50"
 *     responses:
 *       200:
 *         description: Razorpay order created successfully.
 *         content:
 *           application/json:
 *             example:
 *               success: true
 *               data:
 *                 orderId: "order_TrHdfKK9yU7bwS"
 *                 amount: 50000
 *                 currency: "INR"
 *                 keyId: "rzp_test_TrHYmLlskOexBs"
 *       400:
 *         description: Invalid amount or currency.
 */

/**
 * @swagger
 * /api/payments/verify:
 *   post:
 *     summary: Verify Razorpay payment signature & credit wallet
 *     description: |
 *       **Purpose:** Cryptographically verifies the `razorpay_signature` generated by Razorpay using HMAC SHA256
 *       with the `RAZORPAY_KEY_SECRET`. Upon verification, the user's wallet is credited with coins automatically.
 *       **Access Level:** 🔒 Authenticated Session.
 *     tags: [Payments]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - razorpay_order_id
 *               - razorpay_payment_id
 *               - razorpay_signature
 *             properties:
 *               razorpay_order_id:
 *                 type: string
 *                 example: "order_TrHdfKK9yU7bwS"
 *               razorpay_payment_id:
 *                 type: string
 *                 example: "pay_TrHea99812bca"
 *               razorpay_signature:
 *                 type: string
 *                 example: "9a2f7c4e5b6d7a8e9f0c1b2a3d4e5f6a..."
 *     responses:
 *       200:
 *         description: Payment verified successfully and wallet credited.
 *         content:
 *           application/json:
 *             example:
 *               success: true
 *               message: "Payment verified successfully"
 *               data:
 *                 paymentId: "pay_TrHea99812bca"
 *                 coinsCredited: 100
 *                 newWalletBalance: 250
 *       400:
 *         description: Invalid payment signature (potential fraud attempt).
 */

/**
 * @swagger
 * /api/payments/callback:
 *   post:
 *     summary: Handle Razorpay bank redirect callback
 *     description: |
 *       **Purpose:** Webhook/callback endpoint called by the user's bank after 3D-Secure OTP verification.
 *       Redirects the user back to the frontend success or failure page.
 *       **Access Level:** 🌐 Public (Invoked by Razorpay / Bank Gateway).
 *     tags: [Payments]
 *     security: []
 *     responses:
 *       302:
 *         description: Redirects browser to frontend `/dashboard/coins?payment=success`.
 */
